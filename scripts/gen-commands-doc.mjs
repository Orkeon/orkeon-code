#!/usr/bin/env node
// Generate docs/commands.md and docs/fr/commands.md from the slash commands themselves: the
// name and the description each *.cmd.ts declares, and whether it runs synchronously or as an
// async command (a crew run behind a ticket). The pages are never edited by hand. The French
// page has its title, its introduction and its column headings in French; the descriptions are
// the ones the REPL prints, read from the sources, and stay in English, which the page says.
//
//   npm run docs:commands          rewrite both pages
//   node scripts/gen-commands-doc.mjs --check   fail when a page is out of date
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src", "commands");

// The functional folders of src/commands/, in the order the pages list them, with their titles.
const GROUPS = [
  { folder: "session", en: "The session", fr: "La session" },
  { folder: "settings", en: "Settings", fr: "Réglages" },
  { folder: "status", en: "Status and usage", fr: "État et consommation" },
  { folder: "project", en: "The project", fr: "Le projet" },
  { folder: "git", en: "Git and review", fr: "Git et revue" },
  { folder: "dev", en: "The dev workflow", fr: "Le workflow dev" },
  { folder: "memory", en: "Memory", fr: "Mémoire" },
  { folder: "speech", en: "Speech", fr: "Voix" },
];

const commands = [];
for (const entry of readdirSync(dir, { withFileTypes: true, recursive: true })) {
  if (!entry.isFile() || !entry.name.endsWith(".cmd.ts")) continue;
  const folder = relative(dir, entry.parentPath);
  if (!GROUPS.some((g) => g.folder === folder)) {
    console.error(`${relative(root, join(entry.parentPath, entry.name))}: not in a functional folder of src/commands/ (${GROUPS.map((g) => g.folder).join(", ")}).`);
    process.exit(1);
  }
  const file = join(folder, entry.name);
  const src = readFileSync(join(dir, file), "utf8");
  const name = src.match(/\bname:\s*"([^"]+)"/)?.[1] ?? file.replace(/\.cmd\.ts$/, "");
  const raw = src.match(/\bdescription:\s*"((?:[^"\\]|\\.)*)"/)?.[1];
  const description = raw ? JSON.parse(`"${raw}"`) : "(no static description)";
  const kind = /\bdefineAsyncCommand\s*\(/.test(src) ? "async" : "sync";
  const aliases = [...(src.match(/\baliases:\s*\[([^\]]*)\]/)?.[1] ?? "").matchAll(/"([^"]+)"/g)].map((m) => `\`/${m[1]}\``);
  commands.push({ folder, name, description, kind, aliases });
}
commands.sort((a, b) => a.name.localeCompare(b.name));

const cell = (text) => text.replace(/\\/g, "\\\\").replace(/\|/g, "\\|");
const NOTE = "<!-- Generated by scripts/gen-commands-doc.mjs from src/commands/*/*.cmd.ts. Do not edit by hand: run `npm run docs:commands`. -->";

function render({ title, intro, columns, also, lang }) {
  const row = ({ name, description, kind, aliases }) => {
    const suffix = aliases.length > 0 ? ` ${also} ${aliases.join(", ")}.` : "";
    return `| \`/${name}\` | ${kind} | ${cell(description + suffix)} |`;
  };
  const sections = GROUPS.flatMap((g) => [
    "", `## ${g[lang]}`, "", `| ${columns.join(" | ")} |`, "|---|---|---|",
    ...commands.filter((c) => c.folder === g.folder).map(row),
  ]);
  return [`# ${title}`, "", NOTE, "", ...intro, ...sections, ""].join("\n");
}

const pages = [
  {
    path: join(root, "docs", "commands.md"),
    page: render({
      title: "Slash commands",
      intro: [
        `${commands.length} commands, by function (the folders of \`src/commands/\`). Free text typed without a leading \`/\` goes to \`/assistant\`.`,
        "An **async** command starts a crew and returns a ticket; its result is printed when the crew completes.",
      ],
      columns: ["Command", "Kind", "Description"],
      also: "Also",
      lang: "en",
    }),
  },
  {
    path: join(root, "docs", "fr", "commands.md"),
    page: render({
      title: "Commandes",
      intro: [
        `${commands.length} commandes, par fonction (les dossiers de \`src/commands/\`). Le texte libre saisi sans \`/\` initial va à \`/assistant\`.`,
        "Une commande **async** lance un crew et rend un ticket ; son résultat est affiché quand le crew se termine.",
        "Les descriptions sont celles que le REPL affiche, lues dans `src/commands/*/*.cmd.ts` : elles restent en anglais.",
      ],
      columns: ["Commande", "Type", "Description"],
      also: "Aussi",
      lang: "fr",
    }),
  },
];

// The REPL refuses to load a command whose description is longer than 200 characters
// (ScriptCommandLoader: "description exceeds 200 chars"), which only a live start would show.
const MAX_DESCRIPTION = 200;
let stale = 0;
for (const { name, description } of commands) {
  if (description.length > MAX_DESCRIPTION) {
    console.error(`/${name}: description of ${description.length} characters, the REPL loads ${MAX_DESCRIPTION} at most.`);
    stale += 1;
  }
}
for (const { path, page } of pages) {
  const name = relative(root, path);
  if (process.argv.includes("--check")) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (current !== page) {
      console.error(`${name} is out of date: run \`npm run docs:commands\`.`);
      stale += 1;
    } else {
      console.log(`${name}: up to date (${commands.length} commands)`);
    }
  } else {
    writeFileSync(path, page);
    console.log(`${name}: ${commands.length} commands`);
  }
}
if (stale > 0) process.exit(1);

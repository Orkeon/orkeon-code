#!/usr/bin/env node
// Generate docs/commands.md from the slash commands themselves: the name and the
// description each *.cmd.ts declares, and whether it runs synchronously or as an
// async command (a crew run behind a ticket). The page is never edited by hand.
//
//   npm run docs:commands          rewrite docs/commands.md
//   node scripts/gen-commands-doc.mjs --check   fail when the page is out of date
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src", "commands");
const target = join(root, "docs", "commands.md");

const rows = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith(".cmd.ts")).sort()) {
  const src = readFileSync(join(dir, file), "utf8");
  const name = src.match(/\bname:\s*"([^"]+)"/)?.[1] ?? file.replace(/\.cmd\.ts$/, "");
  const raw = src.match(/\bdescription:\s*"((?:[^"\\]|\\.)*)"/)?.[1];
  const description = raw ? JSON.parse(`"${raw}"`) : "(no static description)";
  const kind = /\bdefineAsyncCommand\s*\(/.test(src) ? "async" : "sync";
  rows.push(`| \`/${name}\` | ${kind} | ${description.replace(/\|/g, "\\|")} |`);
}

const page = [
  "# Slash commands",
  "",
  "<!-- Generated by scripts/gen-commands-doc.mjs from src/commands/*.cmd.ts. Do not edit by hand: run `npm run docs:commands`. -->",
  "",
  `${rows.length} commands. Free text typed without a leading \`/\` goes to \`/assistant\`.`,
  "An **async** command starts a crew and returns a ticket; its result is printed when the crew completes.",
  "",
  "| Command | Kind | Description |",
  "|---|---|---|",
  ...rows,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== page) {
    console.error("docs/commands.md is out of date: run `npm run docs:commands`.");
    process.exit(1);
  }
  console.log(`docs/commands.md: up to date (${rows.length} commands)`);
} else {
  writeFileSync(target, page);
  console.log(`docs/commands.md: ${rows.length} commands`);
}
